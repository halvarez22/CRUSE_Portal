export interface OfficialQuotaRow {
  rowIndex: number;
  amount: number;
  termPeriods: number;
  periodicPayment: string;
  requiredIncome: string;
}

function unpackRows(compact: string): OfficialQuotaRow[] {
  return compact.trim().split(';').map((entry) => {
    const [idx, amt, term, pmt, inc] = entry.split('|');
    const dPmt = new Decimal(pmt);
    const computedInc = inc ? inc : dPmt.div(new Decimal('0.30')).toDP(2, Decimal.ROUND_HALF_UP).toFixed(2);
    return {
      rowIndex: new Decimal(idx).toNumber(),
      amount: new Decimal(amt).toNumber(),
      termPeriods: new Decimal(term).toNumber(),
      periodicPayment: dPmt.toFixed(2),
      requiredIncome: computedInc,
    };
  });
}

