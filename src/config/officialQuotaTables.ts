export const OFFICIAL_QUOTA_TABLES: Record<QuotaTableKey, OfficialQuotaRow[]> = {
  normalQuincenalActivos: unpackRows(NORMAL_QUINCENAL_ACTIVOS_RAW),
  normalQuincenalPensionados: unpackRows(NORMAL_QUINCENAL_PENSIONADOS_RAW),
  normalMensualActivos: unpackRows(NORMAL_MENSUAL_ACTIVOS_RAW),
  expressQuincenal: unpackRows(EXPRESS_QUINCENAL_RAW),
  expressMensual: unpackRows(EXPRESS_MENSUAL_RAW),
};

export function getAllowedExpressTerm(amount: number, frequency: 'quincenal' | 'mensual' = 'quincenal'): number {
  const dAmount = new Decimal(amount);
  if (dAmount.lte(5000)) {
    return frequency === 'quincenal' ? 6 : 3;
  }
  if (dAmount.lte(10000)) {
    return frequency === 'quincenal' ? 14 : 7;
  }
  return frequency === 'quincenal' ? 20 : 10;
}

export function resolveQuotaTableKey(
  productId: 'normal' | 'express' | 'especial',
  frequency: 'quincenal' | 'mensual' = 'quincenal',
  borrowerProfile: 'activo' | 'pensionado' = 'activo',
): QuotaTableKey | null {
  if (productId === 'especial') return null;
  if (productId === 'express') {
    return frequency === 'mensual' ? 'expressMensual' : 'expressQuincenal';
  }
  if (frequency === 'mensual') return 'normalMensualActivos';
  return borrowerProfile === 'pensionado' ? 'normalQuincenalPensionados' : 'normalQuincenalActivos';
}

export function lookupOfficialQuotaRow(
  productId: 'normal' | 'express' | 'especial',
  amount: number,
  termPeriods: number,
  frequency: 'quincenal' | 'mensual' = 'quincenal',
  borrowerProfile: 'activo' | 'pensionado' = 'activo',
): OfficialQuotaRow | null {
  const key = resolveQuotaTableKey(productId, frequency, borrowerProfile);
  if (!key) return null;
  const rows = OFFICIAL_QUOTA_TABLES[key];
  return rows.find((r) => r.amount === amount && r.termPeriods === termPeriods) ?? null;
}
